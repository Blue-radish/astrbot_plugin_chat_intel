"""指向本插件的词：只用来判断「这句话是不是在说群聊情报」。

**这里不再做动作判定。** 生成、重跑、重发、取消、查状态全部由模型理解自然语言、
选择工具、由插件执行；插件只保留确定性的校验（私聊、owner、群配置、参数、队列）。

以前这里有一整套「指向词 + 动作词」匹配，用来在模型之前直接接手请求。
问题不在词表够不够全，而在顺序：规则先执行、模型后看到事实，于是
「这份群聊情报总结得真好」会被当成新请求，白跑一次生成。
现在唯一的用途是：**没配 owner 时**提示一次怎么配，别让人对着机器人自说自话。
"""

# 明确指向本插件的词。注意不含「插件」：B站推送、TTS 也都是插件；
# 也不含「总结」这类动作词——那是模型要理解的事，不是字符串能判的事。
ANCHOR_STRONG = ("群聊情报", "情报系统", "情报", "群聊总结", "日报")


def mentions_plugin(text: str) -> bool:
    """这句话有没有指向本插件（只用于配置缺失时的提示）。"""
    if not text:
        return False
    text = text.strip()
    if not text:
        return False
    return any(word in text for word in ANCHOR_STRONG)
